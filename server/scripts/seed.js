function blogSlug(title) {
  return String(title).toLowerCase().replace(/[^a-z0-9\u0b80-\u0bff]+/g, '-').replace(/^-+|-+$/g, '');
}

function quoteLines(...nums) {
  return nums
    .map((n) => {
      const k = kural(n);
      return `> **குறள் ${n}** — *${k.chapterName}*\n>\n> ${k.line1}\n> ${k.line2}\n>\n> *${k.simpleMeaning}*`;
    })
    .join('\n\n');
}

